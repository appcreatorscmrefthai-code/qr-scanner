-- ---------------------------------------------------------------------------
-- 1) ตารางรายการแจ้งแก้ไข (แทนชีต "แจ้งแก้ไข BOM by Line")
-- ---------------------------------------------------------------------------
create sequence if not exists public.bomc_items_no_seq;

create table if not exists public.bomc_items (
  id          bigint generated by default as identity primary key,
  no          bigint default nextval('public.bomc_items_no_seq'),  -- No.
  created_at  timestamptz not null default now(),                  -- วันที่แจ้ง
  reporter    text not null,                                       -- ผู้แจ้ง (ชื่อของผู้ใช้ที่ login)
  rm_code     text,                                                -- รหัสที่เอาไปใช้
  rm_name     text,                                                -- ชื่อวัตถุดิบ
  qty         numeric not null,                                    -- จำนวนที่ใช้
  edit_type   text,                                                -- ชนิดการแก้ไข
  old_code    text,                                                -- รหัสเดิม (ถ้าทราบ)
  fg_code     text,                                                -- รหัสงาน FG
  pd_number   text,                                                -- เลข PD
  fg_model    text,                                                -- ชื่องาน FG
  use_date    date,                                                -- วันที่นำไปใช้
  photo_url   text,                                                -- รูปถ่าย
  note        text,                                                -- หมายเหตุ
  status      text,                                                -- สถานะของงาน
  engineer    text,                                                -- เอ็นจิเนียร์ผู้รับผิดชอบ
  fix_date    text,                                                -- วันที่แก้ไข (บันทึกอัตโนมัติตอนแก้ในเว็บ)
  source      text not null default 'web',                         -- web / excel / legacy
  updated_at  timestamptz not null default now()
);
alter table public.bomc_items add column if not exists created_by uuid;
alter table public.bomc_items add column if not exists updated_by uuid;
alter sequence public.bomc_items_no_seq owned by public.bomc_items.no;
create index if not exists bomc_items_created_idx on public.bomc_items (created_at);

create or replace function public.bomc_touch() returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;
drop trigger if exists bomc_items_touch on public.bomc_items;
create trigger bomc_items_touch before update on public.bomc_items
  for each row execute function public.bomc_touch();

