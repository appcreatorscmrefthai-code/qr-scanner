-- ---------------------------------------------------------------------------
-- 3) ผู้ใช้ + สิทธิ์
-- ---------------------------------------------------------------------------
create table if not exists public.bomc_profiles (
  user_id    uuid primary key references auth.users (id) on delete cascade,
  name       text not null default '',
  role       text not null default 'viewer' check (role in ('viewer', 'edit1', 'edit2', 'admin')),
  active     boolean not null default true,
  updated_at timestamptz not null default now()
);

-- สิทธิ์ของผู้ใช้ที่ login อยู่ (ไม่มีสิทธิ์ / ถูกปิด = null)
create or replace function public.bomc_role() returns text
language sql stable security definer set search_path = public as $$
  select role from public.bomc_profiles where user_id = auth.uid() and active
$$;

create or replace function public.bomc_my_name() returns text
language sql stable security definer set search_path = public as $$
  select nullif(trim(name), '') from public.bomc_profiles where user_id = auth.uid() and active
$$;

-- ข้อมูลของตัวเอง (เว็บใช้หลัง login)
create or replace function public.bomc_me() returns json
language sql stable security definer set search_path = public, auth as $$
  select json_build_object('user_id', u.id, 'email', u.email, 'name', coalesce(p.name, ''),
                           'role', case when p.active then p.role end)
  from auth.users u left join public.bomc_profiles p on p.user_id = u.id
  where u.id = auth.uid()
$$;

-- แจ้งงาน / นำเข้า: ผู้แจ้ง = ชื่อของผู้ใช้ที่ login เสมอ
create or replace function public.bomc_items_stamp() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.source <> 'legacy' then
    new.created_by := auth.uid();
    new.reporter := coalesce(public.bomc_my_name(), nullif(trim(new.reporter), ''), '-');
  end if;
  return new;
end $$;
drop trigger if exists bomc_items_stamp on public.bomc_items;
create trigger bomc_items_stamp before insert on public.bomc_items
  for each row execute function public.bomc_items_stamp();

