-- ---------------------------------------------------------------------------
-- 1) ตารางรายการแจ้งแก้ไข (แทนชีต "แจ้งแก้ไข BOM by Line")
-- ---------------------------------------------------------------------------
create sequence if not exists public.bomc_items_no_seq;

create table if not exists public.bomc_items (
  id          bigint generated by default as identity primary key,
  no          bigint default nextval('public.bomc_items_no_seq'),  -- No.
  created_at  timestamptz not null default now(),                  -- วันที่แจ้ง
  reporter    text not null,                                       -- ผู้แจ้ง
  rm_code     text,                                                -- รหัสที่เอาไปใช้
  rm_name     text,                                                -- ชื่อวัตถุดิบ
  qty         numeric not null,                                    -- จำนวนที่ใช้
  edit_type   text,                                                -- ชนิดการแก้ไข
  old_code    text,                                                -- รหัสเดิม (ถ้าทราบ)
  fg_code     text,                                                -- รหัสงาน FG
  pd_number   text,                                                -- เลข PD
  fg_model    text,                                                -- ชื่องาน FG
  use_date    date,                                                -- วันที่นำไปใช้
  photo_url   text,                                                -- รูปถ่าย
  note        text,                                                -- หมายเหตุ
  status      text,                                                -- สถานะของงาน
  engineer    text,                                                -- เอ็นจิเนียร์ผู้รับผิดชอบ (กรอกใน Excel)
  fix_date    text,                                                -- วันที่แก้ไข (กรอกใน Excel)
  source      text not null default 'web',                         -- web / excel / legacy
  updated_at  timestamptz not null default now()
);
alter sequence public.bomc_items_no_seq owned by public.bomc_items.no;
create index if not exists bomc_items_created_idx on public.bomc_items (created_at);

create or replace function public.bomc_touch() returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;
drop trigger if exists bomc_items_touch on public.bomc_items;
create trigger bomc_items_touch before update on public.bomc_items
  for each row execute function public.bomc_touch();

-- ---------------------------------------------------------------------------
-- 2) ตารางข้อมูลค้นหา (แทนชีต "PD number" และ "Released products")  ส่งขึ้นจาก Excel ด้วย VBA
-- ---------------------------------------------------------------------------
create table if not exists public.bomc_pd_number (
  qr          text primary key,      -- QR  เช่น 3-01-10002WG::TSZ01U00001
  pd_number   text,
  fg_model    text,
  fg_type     text,
  item_number text,
  updated_at  timestamptz not null default now()
);

create table if not exists public.bomc_released_products (
  qr_code      text primary key,     -- QR code  เช่น 1-01-11014::
  item_number  text,
  product_name text,
  bom_unit     text,
  updated_at   timestamptz not null default now()
);
create index if not exists bomc_rp_item_idx on public.bomc_released_products (item_number);

-- ---------------------------------------------------------------------------
-- 3) สิทธิ์ + Row Level Security
-- ---------------------------------------------------------------------------
alter table public.bomc_items             enable row level security;
alter table public.bomc_pd_number         enable row level security;
alter table public.bomc_released_products enable row level security;

revoke all on public.bomc_items, public.bomc_pd_number, public.bomc_released_products from anon;
grant select on public.bomc_items, public.bomc_pd_number, public.bomc_released_products to anon;
-- คนไม่ login แจ้งงานได้ แต่กำหนด id / No. / วันที่แจ้ง / เอ็นจิเนียร์ / วันที่แก้ไข เองไม่ได้
grant insert (reporter, rm_code, rm_name, qty, edit_type, old_code, fg_code, pd_number, fg_model,
              use_date, photo_url, note, status) on public.bomc_items to anon;
grant usage on sequence public.bomc_items_no_seq to anon;
grant usage, select, update on sequence public.bomc_items_no_seq to authenticated;  -- update = ตั้งเลข No. ต่อจากข้อมูลเดิมตอนย้ายข้อมูล
grant all on public.bomc_items, public.bomc_pd_number, public.bomc_released_products to authenticated;

drop policy if exists bomc_items_read   on public.bomc_items;
drop policy if exists bomc_items_report on public.bomc_items;
drop policy if exists bomc_items_auth   on public.bomc_items;
create policy bomc_items_read on public.bomc_items for select to anon, authenticated using (true);
create policy bomc_items_report on public.bomc_items for insert to anon with check (
  source = 'web' and engineer is null and fix_date is null
  and qty > 0 and coalesce(trim(reporter), '') <> ''
  and coalesce(nullif(trim(fg_code), ''), nullif(trim(pd_number), ''), nullif(trim(fg_model), '')) is not null
  and coalesce(nullif(trim(rm_code), ''), nullif(trim(rm_name), '')) is not null
);
create policy bomc_items_auth on public.bomc_items for all to authenticated using (true) with check (true);

drop policy if exists bomc_pd_read on public.bomc_pd_number;
drop policy if exists bomc_pd_auth on public.bomc_pd_number;
create policy bomc_pd_read on public.bomc_pd_number for select to anon, authenticated using (true);
create policy bomc_pd_auth on public.bomc_pd_number for all to authenticated using (true) with check (true);

drop policy if exists bomc_rp_read on public.bomc_released_products;
drop policy if exists bomc_rp_auth on public.bomc_released_products;
create policy bomc_rp_read on public.bomc_released_products for select to anon, authenticated using (true);
create policy bomc_rp_auth on public.bomc_released_products for all to authenticated using (true) with check (true);

-- ---------------------------------------------------------------------------
-- 4) ฟังก์ชันที่เว็บ / VBA เรียก
-- ---------------------------------------------------------------------------

-- คีย์เทียบรายการซ้ำ: รหัสงาน FG + เลข PD + ชื่องาน FG + รหัสที่เอาไปใช้ + จำนวน + รหัสเดิม
create or replace function public.bomc_dupkey(p_fg text, p_pd text, p_model text, p_rm text, p_qty numeric, p_old text)
returns text language sql immutable as $$
  select lower(concat_ws('|', coalesce(trim(p_fg), ''), coalesce(trim(p_pd), ''), coalesce(trim(p_model), ''),
                              coalesce(trim(p_rm), ''), coalesce(trim_scale(p_qty)::text, ''), coalesce(trim(p_old), '')))
$$;

-- เว็บโหลดครั้งเดียวตอนเปิดหน้า: ตาราง PD number + Released products แบบย่อ (เรียกครั้งเดียวไม่ติดลิมิต 1000 แถว)
create or replace function public.bomc_lookup()
returns json language sql stable as $$
  select json_build_object(
    'pd', coalesce((select json_agg(json_build_array(qr, pd_number, fg_model)) from public.bomc_pd_number), '[]'::json),
    'rm', coalesce((select json_agg(json_build_array(qr_code, product_name, bom_unit, item_number))
                    from public.bomc_released_products), '[]'::json)
  )
$$;

-- นำเข้า Excel จากเว็บ (ต้อง login)  ข้ามแถวข้อมูลไม่ครบ และแถวที่ซ้ำกับของเดิมในระบบ
-- ถ้าในไฟล์มีแถวเหมือนกันหลายแถว จะเก็บไว้ครบทุกแถว (ข้ามเท่าจำนวนที่มีในระบบแล้วเท่านั้น)
create or replace function public.bomc_import(p_rows jsonb)
returns json language sql security invoker as $$
  with src as (
    select e.ord,
           nullif(trim(e.j->>'reporter'), '')  as reporter,
           nullif(trim(e.j->>'status'), '')    as status,
           nullif(trim(e.j->>'fg_code'), '')   as fg_code,
           nullif(trim(e.j->>'pd_number'), '') as pd_number,
           nullif(trim(e.j->>'fg_model'), '')  as fg_model,
           nullif(trim(e.j->>'rm_code'), '')   as rm_code,
           nullif(trim(e.j->>'rm_name'), '')   as rm_name,
           nullif(trim(e.j->>'qty'), '')::numeric as qty,
           nullif(trim(e.j->>'old_code'), '')  as old_code,
           nullif(trim(e.j->>'edit_type'), '') as edit_type,
           nullif(trim(e.j->>'use_date'), '')::date as use_date,
           nullif(trim(e.j->>'note'), '')      as note
    from jsonb_array_elements(p_rows) with ordinality as e(j, ord)
  ),
  valid as (
    select * from src
    where reporter is not null and qty > 0
      and coalesce(fg_code, pd_number, fg_model) is not null
      and coalesce(rm_code, rm_name) is not null
  ),
  keyed as (
    select v.*, public.bomc_dupkey(fg_code, pd_number, fg_model, rm_code, qty, old_code) as k,
           row_number() over (partition by public.bomc_dupkey(fg_code, pd_number, fg_model, rm_code, qty, old_code)
                              order by ord) as rn
    from valid v
  ),
  existing as (
    select public.bomc_dupkey(fg_code, pd_number, fg_model, rm_code, qty, old_code) as k, count(*) as c
    from public.bomc_items group by 1
  ),
  ins as (
    insert into public.bomc_items (reporter, status, fg_code, pd_number, fg_model, rm_code, rm_name, qty,
                                   old_code, edit_type, use_date, note, source)
    select reporter, status, fg_code, pd_number, fg_model, rm_code, rm_name, qty,
           old_code, edit_type, use_date, note, 'excel'
    from keyed left join existing x using (k)
    where keyed.rn > coalesce(x.c, 0)
    order by ord
    returning 1
  )
  select json_build_object(
    'imported',  (select count(*) from ins),
    'duplicate', (select count(*) from keyed) - (select count(*) from ins),
    'skipped',   (select count(*) from src) - (select count(*) from valid)
  )
$$;

-- VBA ดึงข้อมูลทั้งหมดลงไฟล์ Excel กลาง: คืนข้อความเดียว แถวคั่นด้วย chr(30) ช่องคั่นด้วย chr(31)
-- ลำดับช่อง = id, No., วันที่แจ้ง, ผู้แจ้ง, รหัสที่เอาไปใช้, ชื่อวัตถุดิบ, จำนวนที่ใช้, ชนิดการแก้ไข, รหัสเดิม,
--            รหัสงาน FG, เลข PD, ชื่องาน FG, วันที่นำไปใช้, รูปถ่าย, หมายเหตุ, สถานะของงาน, เอ็นจิเนียร์, วันที่แก้ไข
create or replace function public.bomc_clean(t text)
returns text language sql immutable as $$
  select coalesce(replace(replace(t, chr(30), ' '), chr(31), ' '), '')
$$;

create or replace function public.bomc_export()
returns text language sql stable security invoker as $$
  select coalesce(string_agg(
    concat_ws(chr(31),
      id::text,
      coalesce(no::text, ''),
      to_char(created_at at time zone 'Asia/Bangkok', 'YYYY-MM-DD HH24:MI:SS'),
      public.bomc_clean(reporter), public.bomc_clean(rm_code), public.bomc_clean(rm_name),
      coalesce(trim_scale(qty)::text, ''),
      public.bomc_clean(edit_type), public.bomc_clean(old_code),
      public.bomc_clean(fg_code), public.bomc_clean(pd_number), public.bomc_clean(fg_model),
      coalesce(to_char(use_date, 'YYYY-MM-DD'), ''),
      public.bomc_clean(photo_url), public.bomc_clean(note), public.bomc_clean(status),
      public.bomc_clean(engineer), public.bomc_clean(fix_date)
    ), chr(30) order by created_at, id), '')
  from public.bomc_items
$$;

-- VBA ส่งค่า สถานะของงาน / เอ็นจิเนียร์ / วันที่แก้ไข ที่แก้ในไฟล์ Excel กลางกลับขึ้นระบบ (แก้เฉพาะแถวที่ค่าเปลี่ยน)
-- p_rows = [{"id":1,"status":"...","engineer":"...","fix_date":"..."}, ...]
create or replace function public.bomc_update_from_excel(p_rows jsonb)
returns json language sql security invoker as $$
  with src as (
    select (j->>'id')::bigint as id,
           nullif(trim(j->>'status'), '')   as status,
           nullif(trim(j->>'engineer'), '') as engineer,
           nullif(trim(j->>'fix_date'), '') as fix_date
    from jsonb_array_elements(p_rows) as j
    where nullif(j->>'id', '') is not null
  ),
  upd as (
    update public.bomc_items b
       set status = s.status, engineer = s.engineer, fix_date = s.fix_date
      from src s
     where b.id = s.id
       and (b.status   is distinct from s.status
         or b.engineer is distinct from s.engineer
         or b.fix_date is distinct from s.fix_date)
    returning 1
  )
  select json_build_object('updated', (select count(*) from upd), 'received', (select count(*) from src))
$$;

-- VBA ย้ายข้อมูลเดิมจากชีต "แจ้งแก้ไข BOM by Line" ขึ้นระบบ (ทำครั้งเดียว ถ้าเคยย้ายแล้วจะไม่ทำซ้ำ)
create or replace function public.bomc_migrate(p_rows jsonb)
returns json language plpgsql security invoker as $$
declare
  v_ins int;
begin
  if exists (select 1 from public.bomc_items where source = 'legacy') then
    return json_build_object('ok', false, 'error', 'เคยย้ายข้อมูลเดิมขึ้นระบบแล้ว');
  end if;

  insert into public.bomc_items (no, created_at, reporter, rm_code, rm_name, qty, edit_type, old_code,
                                 fg_code, pd_number, fg_model, use_date, photo_url, note, status,
                                 engineer, fix_date, source)
  select nullif(trim(j->>'no'), '')::numeric::bigint,
         coalesce(nullif(trim(j->>'created_at'), '')::timestamp at time zone 'Asia/Bangkok', now()),
         coalesce(nullif(trim(j->>'reporter'), ''), '-'),
         nullif(trim(j->>'rm_code'), ''), nullif(trim(j->>'rm_name'), ''),
         coalesce(nullif(trim(j->>'qty'), '')::numeric, 0),
         nullif(trim(j->>'edit_type'), ''), nullif(trim(j->>'old_code'), ''),
         nullif(trim(j->>'fg_code'), ''), nullif(trim(j->>'pd_number'), ''), nullif(trim(j->>'fg_model'), ''),
         nullif(trim(j->>'use_date'), '')::date,
         nullif(trim(j->>'photo_url'), ''), nullif(trim(j->>'note'), ''), nullif(trim(j->>'status'), ''),
         nullif(trim(j->>'engineer'), ''), nullif(trim(j->>'fix_date'), ''),
         'legacy'
  from jsonb_array_elements(p_rows) with ordinality as e(j, ord)
  order by ord;
  get diagnostics v_ins = row_count;

  -- ให้ No. ของรายการใหม่ต่อจากเลขเดิมที่มากที่สุด
  perform setval('public.bomc_items_no_seq', greatest((select coalesce(max(no), 0) from public.bomc_items), 1));
  return json_build_object('ok', true, 'imported', v_ins);
end $$;

revoke all on function public.bomc_lookup()                     from public;
revoke all on function public.bomc_import(jsonb)                from public;
revoke all on function public.bomc_export()                     from public;
revoke all on function public.bomc_update_from_excel(jsonb)     from public;
revoke all on function public.bomc_migrate(jsonb)               from public;
grant execute on function public.bomc_lookup()                  to anon, authenticated;
grant execute on function public.bomc_import(jsonb)             to authenticated;
grant execute on function public.bomc_export()                  to authenticated;
grant execute on function public.bomc_update_from_excel(jsonb)  to authenticated;
grant execute on function public.bomc_migrate(jsonb)            to authenticated;

