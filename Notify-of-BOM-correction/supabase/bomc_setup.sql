-- ---------------------------------------------------------------------------
-- 5) ฟังก์ชันที่เว็บ / VBA เรียก
-- ---------------------------------------------------------------------------

-- คีย์เทียบรายการซ้ำ: รหัสงาน FG + เลข PD + ชื่องาน FG + รหัสที่เอาไปใช้ + จำนวน + รหัสเดิม
create or replace function public.bomc_dupkey(p_fg text, p_pd text, p_model text, p_rm text, p_qty numeric, p_old text)
returns text language sql immutable as $$
  select lower(concat_ws('|', coalesce(trim(p_fg), ''), coalesce(trim(p_pd), ''), coalesce(trim(p_model), ''),
                              coalesce(trim(p_rm), ''), coalesce(trim_scale(p_qty)::text, ''), coalesce(trim(p_old), '')))
$$;

-- เว็บโหลดครั้งเดียวตอนเปิดหน้า: ตาราง PD number + Released products แบบย่อ
create or replace function public.bomc_lookup()
returns json language sql stable as $$
  select json_build_object(
    'pd', coalesce((select json_agg(json_build_array(qr, pd_number, fg_model)) from public.bomc_pd_number), '[]'::json),
    'rm', coalesce((select json_agg(json_build_array(qr_code, product_name, bom_unit, item_number))
                    from public.bomc_released_products), '[]'::json)
  )
$$;

-- นำเข้า Excel จากเว็บ (edit1 ขึ้นไป)  ข้ามแถวข้อมูลไม่ครบ และแถวที่ซ้ำกับของเดิมในระบบ
create or replace function public.bomc_import(p_rows jsonb)
returns json language sql security invoker as $$
  with src as (
    select e.ord,
           nullif(trim(e.j->>'status'), '')    as status,
           nullif(trim(e.j->>'fg_code'), '')   as fg_code,
           nullif(trim(e.j->>'pd_number'), '') as pd_number,
           nullif(trim(e.j->>'fg_model'), '')  as fg_model,
           nullif(trim(e.j->>'rm_code'), '')   as rm_code,
           nullif(trim(e.j->>'rm_name'), '')   as rm_name,
           nullif(trim(e.j->>'qty'), '')::numeric as qty,
           nullif(trim(e.j->>'old_code'), '')  as old_code,
           nullif(trim(e.j->>'edit_type'), '') as edit_type,
           nullif(trim(e.j->>'use_date'), '')::date as use_date,
           nullif(trim(e.j->>'note'), '')      as note
    from jsonb_array_elements(p_rows) with ordinality as e(j, ord)
  ),
  valid as (
    select * from src
    where qty > 0
      and coalesce(fg_code, pd_number, fg_model) is not null
      and coalesce(rm_code, rm_name) is not null
  ),
  keyed as (
    select v.*, public.bomc_dupkey(fg_code, pd_number, fg_model, rm_code, qty, old_code) as k,
           row_number() over (partition by public.bomc_dupkey(fg_code, pd_number, fg_model, rm_code, qty, old_code)
                              order by ord) as rn
    from valid v
  ),
  existing as (
    select public.bomc_dupkey(fg_code, pd_number, fg_model, rm_code, qty, old_code) as k, count(*) as c
    from public.bomc_items group by 1
  ),
  ins as (
    insert into public.bomc_items (reporter, status, fg_code, pd_number, fg_model, rm_code, rm_name, qty,
                                   old_code, edit_type, use_date, note, source)
    select '-', status, fg_code, pd_number, fg_model, rm_code, rm_name, qty,
           old_code, edit_type, use_date, note, 'excel'
    from keyed left join existing x using (k)
    where keyed.rn > coalesce(x.c, 0)
    order by ord
    returning 1
  )
  select json_build_object(
    'imported',  (select count(*) from ins),
    'duplicate', (select count(*) from keyed) - (select count(*) from ins),
    'skipped',   (select count(*) from src) - (select count(*) from valid)
  )
$$;

-- แก้ สถานะของงาน / เอ็นจิเนียร์ผู้รับผิดชอบ (edit2, admin)  ทีละหลายรายการได้
-- ส่ง null = ไม่เปลี่ยนช่องนั้น  วันที่แก้ไข = เวลาที่กดบันทึก (เวลาไทย)
create or replace function public.bomc_set_status(p_ids bigint[], p_status text, p_engineer text)
returns json language plpgsql security definer set search_path = public as $$
declare
  v_n int;
begin
  if coalesce(public.bomc_role(), '') not in ('edit2', 'admin') then
    raise exception 'ไม่มีสิทธิ์แก้ไขสถานะ / เอ็นจิเนียร์';
  end if;
  if p_status is not null and p_status not in ('อยู่ระหว่างดำเนินการ', 'แจ้งแก้ไข', 'แก้ไขแล้ว') then
    raise exception 'สถานะไม่ถูกต้อง: %', p_status;
  end if;
  update public.bomc_items
     set status     = coalesce(p_status, status),
         engineer   = coalesce(nullif(trim(p_engineer), ''), engineer),
         fix_date   = to_char(now() at time zone 'Asia/Bangkok', 'DD/MM/YYYY HH24:MI'),
         updated_by = auth.uid()
   where id = any (p_ids);
  get diagnostics v_n = row_count;
  return json_build_object('updated', v_n);
end $$;

-- VBA ดึงข้อมูลทั้งหมดลงไฟล์ Excel กลาง: คืนข้อความเดียว แถวคั่นด้วย chr(30) ช่องคั่นด้วย chr(31)
create or replace function public.bomc_clean(t text)
returns text language sql immutable as $$
  select coalesce(replace(replace(t, chr(30), ' '), chr(31), ' '), '')
$$;

create or replace function public.bomc_export()
returns text language sql stable security invoker as $$
  select coalesce(string_agg(
    concat_ws(chr(31),
      id::text,
      coalesce(no::text, ''),
      to_char(created_at at time zone 'Asia/Bangkok', 'YYYY-MM-DD HH24:MI:SS'),
      public.bomc_clean(reporter), public.bomc_clean(rm_code), public.bomc_clean(rm_name),
      coalesce(trim_scale(qty)::text, ''),
      public.bomc_clean(edit_type), public.bomc_clean(old_code),
      public.bomc_clean(fg_code), public.bomc_clean(pd_number), public.bomc_clean(fg_model),
      coalesce(to_char(use_date, 'YYYY-MM-DD'), ''),
      public.bomc_clean(photo_url), public.bomc_clean(note), public.bomc_clean(status),
      public.bomc_clean(engineer), public.bomc_clean(fix_date)
    ), chr(30) order by created_at, id), '')
  from public.bomc_items
$$;

-- รุ่น 1 ให้ Excel ส่งค่าสถานะ/เอ็นจิเนียร์ขึ้นระบบ — รุ่น 2 แก้ในเว็บแทน จึงลบทิ้ง (กันค่าเก่าใน Excel ทับค่าใหม่)
drop function if exists public.bomc_update_from_excel(jsonb);

-- VBA ย้ายข้อมูลเดิมจากชีต "แจ้งแก้ไข BOM by Line" ขึ้นระบบ (admin, ทำครั้งเดียว)
create or replace function public.bomc_migrate(p_rows jsonb)
returns json language plpgsql security definer set search_path = public as $$
declare
  v_ins int;
begin
  if coalesce(public.bomc_role(), '') <> 'admin' then
    raise exception 'ย้ายข้อมูลเดิมได้เฉพาะ admin';
  end if;
  if exists (select 1 from public.bomc_items where source = 'legacy') then
    return json_build_object('ok', false, 'error', 'เคยย้ายข้อมูลเดิมขึ้นระบบแล้ว');
  end if;

  insert into public.bomc_items (no, created_at, reporter, rm_code, rm_name, qty, edit_type, old_code,
                                 fg_code, pd_number, fg_model, use_date, photo_url, note, status,
                                 engineer, fix_date, source)
  select nullif(trim(j->>'no'), '')::numeric::bigint,
         coalesce(nullif(trim(j->>'created_at'), '')::timestamp at time zone 'Asia/Bangkok', now()),
         coalesce(nullif(trim(j->>'reporter'), ''), '-'),
         nullif(trim(j->>'rm_code'), ''), nullif(trim(j->>'rm_name'), ''),
         coalesce(nullif(trim(j->>'qty'), '')::numeric, 0),
         nullif(trim(j->>'edit_type'), ''), nullif(trim(j->>'old_code'), ''),
         nullif(trim(j->>'fg_code'), ''), nullif(trim(j->>'pd_number'), ''), nullif(trim(j->>'fg_model'), ''),
         nullif(trim(j->>'use_date'), '')::date,
         nullif(trim(j->>'photo_url'), ''), nullif(trim(j->>'note'), ''), nullif(trim(j->>'status'), ''),
         nullif(trim(j->>'engineer'), ''), nullif(trim(j->>'fix_date'), ''),
         'legacy'
  from jsonb_array_elements(p_rows) with ordinality as e(j, ord)
  order by ord;
  get diagnostics v_ins = row_count;

  perform setval('public.bomc_items_no_seq', greatest((select coalesce(max(no), 0) from public.bomc_items), 1));
  return json_build_object('ok', true, 'imported', v_ins);
end $$;

-- ---------------------------------------------------------------------------
-- 6) ตั้งค่าผู้ใช้ (admin)
-- ---------------------------------------------------------------------------
create or replace function public.bomc_require_admin() returns void
language plpgsql stable security definer set search_path = public as $$
begin
  if coalesce(public.bomc_role(), '') <> 'admin' then
    raise exception 'ต้องเป็น Admin';
  end if;
end $$;

-- รายชื่อผู้ใช้ทั้งหมดใน project (รวมผู้ใช้ BOM Packing ที่ยังไม่มีสิทธิ์ระบบนี้)
create or replace function public.bomc_admin_users()
returns json language plpgsql security definer set search_path = public, auth as $$
begin
  perform public.bomc_require_admin();
  return coalesce((
    select json_agg(json_build_object(
             'user_id', u.id, 'email', u.email, 'name', coalesce(p.name, ''),
             'role', coalesce(p.role, ''), 'active', coalesce(p.active, false),
             'last_sign_in_at', u.last_sign_in_at)
           order by (p.user_id is null), p.role, p.name, u.email)
    from auth.users u left join public.bomc_profiles p on p.user_id = u.id), '[]'::json);
end $$;

-- ตั้งชื่อ / สิทธิ์ / เปิด-ปิดการใช้งาน  (p_role = '' คือถอนสิทธิ์ระบบนี้)
create or replace function public.bomc_admin_save_user(p_user uuid, p_name text, p_role text, p_active boolean)
returns json language plpgsql security definer set search_path = public as $$
begin
  perform public.bomc_require_admin();
  if p_user = auth.uid() and (coalesce(p_role, '') <> 'admin' or not coalesce(p_active, false)) then
    raise exception 'ลดสิทธิ์หรือปิดบัญชีของตัวเองไม่ได้';
  end if;
  if coalesce(p_role, '') = '' then
    delete from public.bomc_profiles where user_id = p_user;
  else
    insert into public.bomc_profiles (user_id, name, role, active, updated_at)
    values (p_user, trim(coalesce(p_name, '')), p_role, coalesce(p_active, true), now())
    on conflict (user_id) do update
      set name = excluded.name, role = excluded.role, active = excluded.active, updated_at = now();
  end if;
  return json_build_object('ok', true);
end $$;

-- สร้างผู้ใช้ใหม่จากเว็บ  p_login = ชื่อผู้ใช้สั้นๆ (เติม @bomc.local ให้) หรืออีเมล
create or replace function public.bomc_admin_create_user(p_login text, p_password text, p_name text, p_role text)
returns json language plpgsql security definer set search_path = public, auth, extensions as $$
declare
  v_email text := lower(trim(coalesce(p_login, '')));
  v_id uuid := gen_random_uuid();
  c text;
begin
  perform public.bomc_require_admin();
  if v_email = '' then raise exception 'กรุณาระบุชื่อผู้ใช้'; end if;
  if position('@' in v_email) = 0 then v_email := v_email || '@bomc.local'; end if;
  if length(coalesce(p_password, '')) < 6 then raise exception 'รหัสผ่านต้องมีอย่างน้อย 6 ตัวอักษร'; end if;
  if p_role not in ('viewer', 'edit1', 'edit2', 'admin') then raise exception 'สิทธิ์ไม่ถูกต้อง'; end if;
  if exists (select 1 from auth.users where lower(email) = v_email) then
    raise exception 'มีผู้ใช้ % อยู่แล้ว', v_email;
  end if;

  insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
                          raw_app_meta_data, raw_user_meta_data, created_at, updated_at)
  values ('00000000-0000-0000-0000-000000000000', v_id, 'authenticated', 'authenticated', v_email,
          extensions.crypt(p_password, extensions.gen_salt('bf')), now(),
          '{"provider":"email","providers":["email"]}'::jsonb, jsonb_build_object('name', trim(coalesce(p_name, ''))),
          now(), now());
  -- ช่อง token ที่ระบบ login อ่านเป็นข้อความ ต้องไม่เป็น null
  foreach c in array array['confirmation_token', 'recovery_token', 'email_change_token_new', 'email_change',
                           'email_change_token_current', 'phone_change', 'phone_change_token', 'reauthentication_token']
  loop
    if exists (select 1 from information_schema.columns
               where table_schema = 'auth' and table_name = 'users' and column_name = c) then
      execute format('update auth.users set %I = '''' where id = $1 and %I is null', c, c) using v_id;
    end if;
  end loop;

  insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
  values (gen_random_uuid(), v_id, v_id::text,
          jsonb_build_object('sub', v_id::text, 'email', v_email, 'email_verified', true),
          'email', now(), now(), now());

  insert into public.bomc_profiles (user_id, name, role, active) values (v_id, trim(coalesce(p_name, '')), p_role, true);
  return json_build_object('ok', true, 'user_id', v_id, 'email', v_email);
end $$;

-- ตั้งรหัสผ่านใหม่ให้ผู้ใช้
create or replace function public.bomc_admin_set_password(p_user uuid, p_password text)
returns json language plpgsql security definer set search_path = public, auth, extensions as $$
begin
  perform public.bomc_require_admin();
  if length(coalesce(p_password, '')) < 6 then raise exception 'รหัสผ่านต้องมีอย่างน้อย 6 ตัวอักษร'; end if;
  update auth.users set encrypted_password = extensions.crypt(p_password, extensions.gen_salt('bf')), updated_at = now()
   where id = p_user;
  return json_build_object('ok', true);
end $$;

-- ตั้ง admin คนแรก (รันใน SQL Editor เท่านั้น)
create or replace function public.bomc_make_admin(p_email text, p_name text)
returns text language plpgsql security definer set search_path = public, auth as $$
declare
  v_id uuid;
begin
  select id into v_id from auth.users where lower(email) = lower(trim(p_email));
  if v_id is null then raise exception 'ไม่พบผู้ใช้ %', p_email; end if;
  insert into public.bomc_profiles (user_id, name, role, active) values (v_id, trim(p_name), 'admin', true)
  on conflict (user_id) do update set name = excluded.name, role = 'admin', active = true, updated_at = now();
  return 'ตั้ง ' || p_email || ' เป็น admin แล้ว';
end $$;

